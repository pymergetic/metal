static uint16_t argb_to_rgb565(uint32_t argb) {
    uint32_t r = (argb >> 16) & 0xFF;
    uint32_t g = (argb >> 8) & 0xFF;
    uint32_t b = argb & 0xFF;
    return (uint16_t)(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3));
}

int32_t pm_metal_draw_soft_init(pm_metal_draw_surface_t *s, uint8_t *buf,
                                uint32_t width, uint32_t height, uint8_t bpp) {
    if (s == NULL || buf == NULL || width == 0 || height == 0) {
        return -1;
    }
    if (bpp != 16 && bpp != 32) {
        return -1;
    }
    s->pixels = buf;
    s->width = width;
    s->height = height;
    s->bpp = bpp;
    s->stride = width * (bpp / 8u);
    memset(buf, 0, (size_t)s->stride * (size_t)height);
    return 0;
}

void pm_metal_draw_fill(pm_metal_draw_surface_t *s, uint32_t argb) {
    uint32_t x, y;
    if (s == NULL || s->pixels == NULL) {
        return;
    }
    for (y = 0; y < s->height; y++) {
        for (x = 0; x < s->width; x++) {
            pm_metal_draw_pixel(s, (int32_t)x, (int32_t)y, argb);
        }
    }
}

void pm_metal_draw_pixel(pm_metal_draw_surface_t *s, int32_t x, int32_t y, uint32_t argb) {
    uint8_t *row;
    if (s == NULL || s->pixels == NULL) {
        return;
    }
    if (x < 0 || y < 0 || (uint32_t)x >= s->width || (uint32_t)y >= s->height) {
        return;
    }
    row = s->pixels + (size_t)y * (size_t)s->stride;
    if (s->bpp == 16) {
        uint16_t *p = (uint16_t *)(void *)row;
        p[x] = argb_to_rgb565(argb);
    } else {
        uint32_t *p = (uint32_t *)(void *)row;
        p[x] = argb;
    }
}

void pm_metal_draw_glyph8(pm_metal_draw_surface_t *s, int32_t x, int32_t y,
                          char ch, uint32_t fg, uint32_t bg) {
    const uint8_t *glyph;
    int row, col;
    unsigned char uc;

    if (s == NULL) {
        return;
    }
    uc = (unsigned char)ch;
    if (uc < 0x20u || uc > 0x7Eu) {
        uc = (unsigned char)'?';
    }
    glyph = font8x8_basic[uc - 0x20u];
    for (row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (col = 0; col < 8; col++) {
            uint32_t color = (bits & (uint8_t)(0x80u >> col)) ? fg : bg;
            pm_metal_draw_pixel(s, x + col, y + row, color);
        }
    }
}

void pm_metal_draw_text8(pm_metal_draw_surface_t *s, int32_t x, int32_t y,
                         const char *text, uint32_t fg, uint32_t bg) {
    int32_t cx = x;
    if (s == NULL || text == NULL) {
        return;
    }
    while (*text != '\0') {
        if (*text == '\n') {
            cx = x;
            y += 8;
            text++;
            continue;
        }
        pm_metal_draw_glyph8(s, cx, y, *text, fg, bg);
        cx += 8;
        text++;
    }
}

uint32_t pm_metal_draw_checksum(const pm_metal_draw_surface_t *s) {
    uint32_t sum = 0;
    size_t n, i;
    if (s == NULL || s->pixels == NULL) {
        return 0;
    }
    n = (size_t)s->stride * (size_t)s->height;
    for (i = 0; i < n; i++) {
        sum = (sum * 131u) + (uint32_t)s->pixels[i];
    }
    return sum;
}
